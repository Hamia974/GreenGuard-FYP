"""
schemas.py
----------
These classes define the EXACT shape of the request and response JSON.
This is the most important file in the whole module — it is what makes
sure we never accidentally rename a field or change the structure.

If you ever need to change a field name, do NOT edit this file directly.
First check with the Project Manager / Backend dev, per the delivery spec.
"""

from typing import Optional

from pydantic import BaseModel, Field


# ---------- REQUEST ----------

class WeatherRequest(BaseModel):
    """What the Backend sends us."""
    latitude: float = Field(..., ge=-90, le=90, description="Farm latitude")
    longitude: float = Field(..., ge=-180, le=180, description="Farm longitude")
    farm_id: str = Field(default="unknown", description="Optional farm identifier, echoed back in the response")


# ---------- RESPONSE ----------

class WeatherData(BaseModel):
    temperature: float
    humidity: float
    rainfall_last_7_days_mm: float
    wind_speed: float


class WeatherUnits(BaseModel):
    """Fixed units for each `weather` field. Values never change per-request —
    this exists so the JSON is self-describing instead of relying on Backend
    to hardcode units from documentation alone."""
    temperature: str = "celsius"
    humidity: str = "percent"
    rainfall_last_7_days_mm: str = "mm"
    wind_speed: str = "m/s"


class RiskAssessment(BaseModel):
    fungal_disease_risk: str
    fungal_disease_reason: str
    heat_stress_risk: str
    heat_stress_reason: str
    drought_risk: str
    drought_reason: str


class ForecastData(BaseModel):
    """Next-day forecast from the LSTM (see api/lstm_forecast.py). Additive
    only -- unrelated to and does not influence `weather` or
    `risk_assessment` above."""
    temperature: float
    humidity: float
    rainfall_mm: float


class WeatherRiskResponse(BaseModel):
    """What we send back. Must exactly match REST_API_SPEC.md Module 3 output."""
    farm_id: str
    timestamp: str
    weather: WeatherData
    units: WeatherUnits = WeatherUnits()
    risk_assessment: RiskAssessment
    forecast: Optional[ForecastData] = None
    predicted_risk_assessment: Optional[RiskAssessment] = None
